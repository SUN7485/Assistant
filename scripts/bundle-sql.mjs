// Joins every migration, oldest first, into supabase/install.sql: the one file a new Supabase project needs.
//   node scripts/bundle-sql.mjs          writes it
//   node scripts/bundle-sql.mjs --check  fails if it is out of date (CI runs this)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'

const dir = new URL('../supabase/migrations/', import.meta.url)
const out = new URL('../supabase/install.sql', import.meta.url)
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
const text =
  `-- Everything a NEW Supabase project needs, in one file: paste it into SQL Editor and press Run, once.\n` +
  `-- A project that is already running takes only the newer files in supabase/migrations instead.\n` +
  `-- Generated by "npm run db:bundle" from: ${files.join(', ')}. Do not edit by hand.\n` +
  files.map((f) => `\n-- ===================== ${f} =====================\n\n${readFileSync(new URL(f, dir), 'utf8').trim()}\n`).join('')

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    console.error('supabase/install.sql is out of date. Run: npm run db:bundle')
    process.exit(1)
  }
  console.log('supabase/install.sql is up to date')
} else {
  writeFileSync(out, text)
  console.log(`wrote supabase/install.sql from ${files.length} migrations`)
}
